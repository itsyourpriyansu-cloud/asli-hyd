# Build credits.html (the footer's "Photo credits" page) from the three SOURCES files.
# CC BY / BY-SA photos need a visible credit, and the homepage no longer shows them inline,
# so re-run this whenever a SOURCES file changes:
#
#   python -I tools/assets/credits.py
#
# Only the headings and credit tables are published: the notes around them in the SOURCES files are
# for the team. A small Markdown subset is enough: # / ## headings, pipe tables, **bold**, `code`, [links](url).
import html, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCES = ['assets/img/SOURCES.md', 'assets/img/quick/SOURCES.md', 'VIDEO-SOURCES.md']


def inline(t):
    # The client's own photos are credited to Asli Hyderabad on the public page.
    t = t.replace("client's site", 'Asli Hyderabad').replace('client to confirm', '© Asli Hyderabad')
    t = html.escape(t, quote=False)
    t = re.sub(r'`([^`]+)`', r'<code>\1</code>', t)
    t = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', t)
    t = re.sub(r'\[([^\]]+)\]\(([^)\s]+)\)', lambda m: f'<a href="{m.group(2)}" target="_blank" rel="noopener">{m.group(1)}</a>', t)
    return t


def convert(md):
    out, para, rows = [], [], []

    def flush():
        para.clear()
        if rows:
            head, body = rows[0], [r for r in rows[2:]]
            out.append('<div class="cr-table"><table><thead><tr>' + ''.join(f'<th>{inline(c)}</th>' for c in head) + '</tr></thead><tbody>'
                       + ''.join('<tr>' + ''.join(f'<td>{inline(c)}</td>' for c in r) + '</tr>' for r in body) + '</tbody></table></div>')
            rows.clear()

    for line in md.splitlines():
        s = line.strip()
        if s.startswith('|'):
            if para: flush()
            rows.append([c.strip() for c in s.strip('|').split('|')])
            continue
        if rows: flush()
        if not s or s == '---':
            flush()
        elif s.startswith('## '):
            flush(); out.append('<h3>' + inline(s[3:]) + '</h3>')
        elif s.startswith('# '):
            flush(); out.append('<h2>' + inline(s[2:]) + '</h2>')
        elif s.startswith('- ') or re.match(r'\d+\. ', s):
            flush()
        else:
            para.append(s)
    flush()
    return '\n'.join(out)


